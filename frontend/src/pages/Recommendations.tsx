import { Check, LoaderCircle, Search, X } from "lucide-react";
import { useMemo, useState } from "react";

import { Card, PageState, SectionHeader, StatusBadge } from "../components/ui";
import { useAuth } from "../context/AuthContext";
import { useApi } from "../hooks/useApi";
import { api } from "../lib/api";
import { dateTime, money, percent } from "../lib/format";

import type { Product, Recommendation } from "../types";

export function Recommendations() {
  // Fetch data
  const recs = useApi<Recommendation[]>("/price-recommendations?limit=1000");

  const products = useApi<Product[]>("/products?limit=1000");

  // Authentication and permissions
  const { user } = useAuth();

  const canReview = user?.role === "approver" || user?.role === "admin";

  // Component state
  const [filter, setFilter] = useState("all");
  const [search, setSearch] = useState("");
  const [acting, setActing] = useState("");
  const [error, setError] = useState("");

  // Filter and sort recommendations
  const rows = useMemo(
    () =>
      (recs.data || [])
        .filter((recommendation) => {
          const matchesStatus =
            filter === "all" || recommendation.status === filter;

          const productName =
            products.data?.find(
              (product) => product.product_id === recommendation.product_id,
            )?.product_name || "";

          const matchesSearch = productName
            .toLowerCase()
            .includes(search.toLowerCase());

          return matchesStatus && matchesSearch;
        })
        .sort((a, b) => b.generated_at.localeCompare(a.generated_at)),
    [recs.data, products.data, filter, search],
  );

  // Approve or reject a recommendation
  async function review(
    recommendation: Recommendation,
    action: "approve" | "reject",
  ) {
    const reason = window.prompt(
      `${action === "approve" ? "Approval" : "Rejection"} note (optional):`,
    );

    // User cancelled the prompt
    if (reason === null) {
      return;
    }

    setActing(recommendation.recommendation_id + action);
    setError("");

    try {
      await api.post(
        `/price-recommendations/${recommendation.recommendation_id}/${action}`,
        {
          reason: reason || null,
        },
      );

      await recs.refresh();
    } catch (error) {
      setError(error instanceof Error ? error.message : "Action failed");
    } finally {
      setActing("");
    }
  }

  // Loading state
  if (recs.loading || products.loading) {
    return <PageState loading />;
  }

  // Error state
  if (recs.error || products.error) {
    return <PageState error={recs.error || products.error} />;
  }

  return (
    <Card>
      {/* Section header */}
      <SectionHeader
        title="Price recommendations"
        subtitle="Review pricing opportunities generated by your rules"
      />

      {/* Status filters */}
      <div className="status-tabs">
        {["all", "pending", "approved", "rejected", "applied"].map((status) => (
          <button
            key={status}
            className={filter === status ? "active" : ""}
            onClick={() => setFilter(status)}
          >
            {status}

            <span>
              {status === "all"
                ? recs.data?.length
                : recs.data?.filter(
                    (recommendation) => recommendation.status === status,
                  ).length}
            </span>
          </button>
        ))}
      </div>

      {/* Search */}
      <div className="toolbar">
        <label className="search">
          <Search />

          <input
            value={search}
            onChange={(event) => setSearch(event.target.value)}
            placeholder="Search by product…"
          />
        </label>
      </div>

      {/* Action error */}
      {error && <div className="form-error">{error}</div>}

      {/* Recommendations table */}
      {!rows.length ? (
        <PageState empty="No recommendations match this view." />
      ) : (
        <div className="table-wrap">
          <table>
            <thead>
              <tr>
                <th>Product</th>
                <th>Current price</th>
                <th>Recommended</th>
                <th>Expected change</th>
                <th>Reason / rule</th>
                <th>Status</th>
                <th>Generated</th>

                {canReview && <th>Actions</th>}
              </tr>
            </thead>

            <tbody>
              {rows.map((recommendation) => {
                const product = products.data?.find(
                  (item) => item.product_id === recommendation.product_id,
                );

                const change =
                  ((Number(recommendation.recommended_price) -
                    Number(recommendation.current_price || 0)) /
                    Number(recommendation.current_price || 1)) *
                  100;

                return (
                  <tr key={recommendation.recommendation_id}>
                    {/* Product */}
                    <td>
                      <strong>
                        {product?.product_name || "Unknown product"}
                      </strong>

                      <small className="table-sub">{product?.sku}</small>
                    </td>

                    {/* Current price */}
                    <td>{money(recommendation.current_price)}</td>

                    {/* Recommended price */}
                    <td>
                      <strong>{money(recommendation.recommended_price)}</strong>
                    </td>

                    {/* Expected price change */}
                    <td>
                      <span className={change >= 0 ? "positive" : "negative"}>
                        {percent(change)}
                      </span>
                    </td>

                    {/* Recommendation reason */}
                    <td className="reason-cell">
                      {recommendation.recommendation_reason}
                    </td>

                    {/* Status */}
                    <td>
                      <StatusBadge status={recommendation.status} />
                    </td>

                    {/* Generated date */}
                    <td>{dateTime(recommendation.generated_at)}</td>

                    {/* Approval / rejection actions */}
                    {canReview && (
                      <td>
                        {recommendation.status === "pending" ? (
                          <div className="actions">
                            {/* Approve */}
                            <button
                              className="action approve"
                              title="Approve"
                              disabled={!!acting}
                              onClick={() =>
                                void review(recommendation, "approve")
                              }
                            >
                              {acting ===
                              recommendation.recommendation_id + "approve" ? (
                                <LoaderCircle className="spin" />
                              ) : (
                                <Check />
                              )}
                            </button>

                            {/* Reject */}
                            <button
                              className="action reject"
                              title="Reject"
                              disabled={!!acting}
                              onClick={() =>
                                void review(recommendation, "reject")
                              }
                            >
                              {acting ===
                              recommendation.recommendation_id + "reject" ? (
                                <LoaderCircle className="spin" />
                              ) : (
                                <X />
                              )}
                            </button>
                          </div>
                        ) : (
                          "—"
                        )}
                      </td>
                    )}
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>
      )}

      {/* Read-only permission notice */}
      {!canReview && (
        <p className="permission-note">
          Your {user?.role} role has read-only access to recommendations.
        </p>
      )}
    </Card>
  );
}
